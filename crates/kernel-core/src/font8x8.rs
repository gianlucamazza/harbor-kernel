//! 8×8 bitmap font for ASCII printable characters (0x20–0x7E).
//!
//! Derived from the public-domain `font8x8` basic set (Marcel Sondaar /
//! public domain). Each glyph is 8 rows; bit 0 is the leftmost pixel.

/// Glyph height and width in pixels.
pub const GLYPH_W: u16 = 8;
pub const GLYPH_H: u16 = 8;

/// First code point stored in [`BASIC`].
pub const FIRST: u8 = 0x20;
/// Number of glyphs in [`BASIC`].
pub const COUNT: usize = 95; // 0x20..=0x7E

/// Return the 8 row bytes for `ch`, or the glyph for `'?'` if out of range.
pub fn glyph(ch: u8) -> &'static [u8; 8] {
    let idx = if (FIRST..FIRST + COUNT as u8).contains(&ch) {
        (ch - FIRST) as usize
    } else {
        // '?'
        (b'?' - FIRST) as usize
    };
    &BASIC[idx]
}

/// True if bit `col` (0 = left) is set in row byte `row`.
#[inline]
pub const fn pixel_set(row: u8, col: u8) -> bool {
    (row >> col) & 1 != 0
}

