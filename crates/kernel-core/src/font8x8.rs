#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn space_is_blank() {
        assert!(glyph(b' ').iter().all(|&r| r == 0));
    }

    #[test]
    fn digit_zero_has_ink() {
        assert!(glyph(b'0').iter().any(|&r| r != 0));
    }

    #[test]
    fn out_of_range_uses_question() {
        assert_eq!(glyph(0x01), glyph(b'?'));
    }
}
